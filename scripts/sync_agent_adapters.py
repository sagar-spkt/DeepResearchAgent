"""Generate portable native adapters; installation is a separate explicit action."""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "Generated by scripts/sync_agent_adapters.py; do not edit."


def read_metadata(path):
    """Read our deliberately restricted YAML frontmatter: JSON values per line."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        raise ValueError(f"{path}: missing frontmatter")
    header, body = text[4:].split("\n---\n", 1)
    data = {}
    for line in header.splitlines():
        key, value = line.split(":", 1)
        if key in data or not re.fullmatch(r"[A-Za-z][A-Za-z-]*", key):
            raise ValueError(f"{path}: invalid/duplicate metadata key")
        data[key] = json.loads(value)
    for key in ("name", "description"):
        if not isinstance(data.get(key), str) or not data[key].strip():
            raise ValueError(f"{path}: missing {key}")
    if not re.fullmatch(r"[a-z][a-z0-9-]{0,63}", data["name"]):
        raise ValueError(f"{path}: invalid name")
    if not body.strip():
        raise ValueError(f"{path}: empty instructions")
    return data, body.strip()


def frontmatter(data):
    return "---\n" + "".join(f"{k}: {json.dumps(v)}\n" for k, v in data.items()) + "---\n\n"


def expected_files(root):
    outputs = {}
    required_skills = {
        "plan-change",
        "implement-change",
        "review-change",
        "validate-change",
        "release-change",
    }
    required_roles = {"implementer", "reviewer", "test-validator", "platform-reviewer"}
    if {
        p.parent.name for p in (root / "agent-config/skills").glob("*/SKILL.md")
    } != required_skills:
        raise ValueError("Canonical skill set is incomplete or unexpected")
    if {p.stem for p in (root / "agent-config/roles").glob("*.md")} != required_roles:
        raise ValueError("Canonical role set is incomplete or unexpected")
    for path in sorted((root / "agent-config/skills").glob("*/SKILL.md")):
        meta, body = read_metadata(path)
        name = meta["name"]
        if name != path.parent.name or set(meta) != {"name", "description"}:
            raise ValueError(f"{path}: skill contract mismatch")
        source = f"agent-config/skills/{name}/SKILL.md"
        wrapper = (
            frontmatter(meta)
            + f"<!-- {GENERATED} -->\n\nRead and follow `{source}` from the repository root before performing this workflow. Read `AGENTS.md` first. This adapter grants no additional permissions.\n"
        )
        outputs[f"claude/skills/{name}/SKILL.md"] = wrapper
        # Full skill content supports normal Codex/Antigravity discovery.
        outputs[f"shared/skills/{name}/SKILL.md"] = (
            frontmatter(meta) + f"<!-- {GENERATED} -->\n\n{body}\n"
        )
    for path in sorted((root / "agent-config/roles").glob("*.md")):
        meta, body = read_metadata(path)
        name = meta["name"]
        if name != path.stem or set(meta) != {"name", "description", "skill"}:
            raise ValueError(f"{path}: role contract mismatch")
        if not (root / "agent-config/skills" / meta["skill"] / "SKILL.md").is_file():
            raise ValueError(f"{path}: missing skill")
        instruction = f"{GENERATED}\nRead AGENTS.md and agent-config/roles/{name}.md from the repository root.\n\n{body}"
        outputs[f"codex/agents/{name}.toml"] = (
            f"# {GENERATED}\nname = {json.dumps(name)}\n"
            f"description = {json.dumps(meta['description'])}\n"
            f"developer_instructions = {json.dumps(instruction)}\n"
        )
        claude = {"name": name, "description": meta["description"]}
        if name in {"reviewer", "platform-reviewer"}:
            claude["tools"] = ["Read", "Grep", "Glob"]
        elif name == "test-validator":
            claude["tools"] = ["Read", "Grep", "Glob", "Bash"]
        outputs[f"claude/agents/{name}.md"] = frontmatter(claude) + instruction + "\n"
        agy = {
            "name": name,
            "description": meta["description"],
            "subagent": True,
            "mainAgent": False,
        }
        agy["tools"] = ["view_file", "grep_search"]
        if name in {"implementer", "test-validator"}:
            agy["tools"].append("run_command")
        if name == "implementer":
            agy["tools"].append("replace_file_content")
        outputs[f"antigravity/agents/{name}.md"] = frontmatter(agy) + instruction + "\n"
    return outputs


def destinations(root, outputs, install):
    selected = {}
    for relative, text in outputs.items():
        tool, rest = relative.split("/", 1)
        if install == "claude" and tool == "claude":
            selected[root / ".claude" / rest] = text
        elif install == "codex" and tool == "codex":
            selected[root / ".codex" / rest] = text
        elif install == "antigravity" and tool == "antigravity":
            selected[root / ".agents" / rest] = text
        elif install in {"codex", "antigravity"} and tool == "shared":
            selected[root / ".agents" / rest] = text
    return selected


def sync(root=ROOT, check=False, install=None):
    outputs = expected_files(root)
    export = root / "agent-config/adapters"
    stale = []
    selected = destinations(root, outputs, install) if install else {}
    for path in [*(export / relative for relative in outputs), *selected]:
        if not path.resolve().is_relative_to(root.resolve()):
            raise ValueError(f"Refusing path outside repository (possibly a symlink): {path}")
    # Preflight every destination before any export/install writes.
    for path in selected:
        if path.exists() and GENERATED not in path.read_text(encoding="utf-8"):
            raise ValueError(f"Refusing to overwrite unmanaged file: {path}")
    for relative, text in outputs.items():
        path = export / relative
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if export.exists():
        extras = {
            p.relative_to(export).as_posix() for p in export.rglob("*") if p.is_file()
        } - outputs.keys()
        if extras:
            raise ValueError(f"Unexpected adapter files; remove deliberately: {sorted(extras)}")
    if check:
        for prefix, directory in (
            ("claude", ".claude"),
            ("codex", ".codex"),
            ("antigravity", ".agents"),
            ("shared", ".agents"),
        ):
            group = {
                root / directory / relative.split("/", 1)[1]: text
                for relative, text in outputs.items()
                if relative.startswith(prefix + "/")
            }
            # An unrelated user directory does not imply installation of this setup.
            active = any(
                path.is_file() and GENERATED in path.read_text(encoding="utf-8") for path in group
            )
            if active:
                for path, text in group.items():
                    if not path.is_file() or path.read_text(encoding="utf-8") != text:
                        stale.append(str(path.relative_to(root)))
    if stale:
        raise ValueError("Adapter drift: " + ", ".join(stale))
    for destination, text in selected.items():
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(text, encoding="utf-8")
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--install", choices=["codex", "claude", "antigravity"])
    args = parser.parse_args()
    if args.check and args.install:
        parser.error("--check cannot install files")
    try:
        outputs = sync(check=args.check, install=args.install)
    except (OSError, ValueError) as exc:
        print(exc, file=sys.stderr)
        return 1
    print(
        f"{'Checked' if args.check else 'Generated'} {len(outputs)} adapters"
        + (f"; installed {args.install}" if args.install else "")
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
