def permits(policy, action, resource, context=None):
    """Evaluate only the Allow statements/operators generated by backup_policy."""
    context = context or {}
    for statement in policy["Statement"]:
        if action not in statement["Action"] or not any(
            fnmatch.fnmatchcase(resource, pattern) for pattern in statement["Resource"]
        ):
            continue
        matched = True
        for operator, values in statement.get("Condition", {}).items():
            for key, expected in values.items():
                actual = context.get(key)
                if operator == "StringEquals":
                    matched &= actual == expected
                elif operator == "ForAllValues:StringEquals":
                    matched &= all(value in expected for value in (actual or []))
                elif operator == "Null":
                    matched &= (actual is None) == (expected == "true")
                else:
                    raise AssertionError("Unsupported operator: " + operator)
        if matched:
            return True
    return False


class BackupPolicyTests(unittest.TestCase):
    def setUp(self):
        self.policy = backup_policy(CONFIG)

    def test_session_writes_require_encryption_and_exact_prefix(self):
        target = "arn:aws:s3:::" + CONFIG["backup_bucket"] + "/sessions/staging/session-1/valkey/dump.rdb"
        context = {"s3:x-amz-server-side-encryption": "AES256"}
        self.assertTrue(permits(self.policy, "s3:PutObject", target, context))
        self.assertTrue(permits(self.policy, "s3:PutObject", target.replace("valkey/dump.rdb", "receipts/backup.json"), context))
        for other_object in ["clickhouse/data.bin", "receipts/shutdown.json", "valkey/other.rdb"]:
            self.assertFalse(permits(self.policy, "s3:PutObject", target.replace("valkey/dump.rdb", other_object), context))
        self.assertFalse(permits(self.policy, "s3:PutObject", target))
        for replacement in ["production", "session-2", "session-10"]:
            wrong = target.replace("staging" if replacement == "production" else "session-1", replacement)
            self.assertFalse(permits(self.policy, "s3:PutObject", wrong, context))
        self.assertFalse(permits(self.policy, "s3:PutObject", target.replace("backups", "documents"), context))

    def test_retained_inventory_and_version_reads_are_scoped(self):
        for key in ["document_bucket", "trace_bucket", "backup_bucket"]:
            bucket = "arn:aws:s3:::" + CONFIG[key]
            self.assertTrue(permits(self.policy, "s3:ListBucketVersions", bucket))
            self.assertTrue(permits(self.policy, "s3:GetObjectVersion", bucket + "/some/object"))
            self.assertFalse(permits(self.policy, "s3:GetObjectVersion", bucket.replace("staging", "production") + "/some/object"))

    def test_lock_mutation_never_changes_admission_or_month_reservations(self):
        table = "arn:aws:dynamodb:us-east-1:123456789012:table/deepresearch-control"
        for action in ["dynamodb:UpdateItem", "dynamodb:DeleteItem"]:
            self.assertTrue(permits(self.policy, action, table, {"dynamodb:LeadingKeys": ["lifecycle-lock"]}))
            for keys in [None, ["active-session"], ["month#2026-11"], ["completion#staging#session-1"], ["lifecycle-lock", "active-session"]]:
                context = {} if keys is None else {"dynamodb:LeadingKeys": keys}
                self.assertFalse(permits(self.policy, action, table, context))
        self.assertTrue(permits(self.policy, "dynamodb:GetItem", table, {"dynamodb:LeadingKeys": ["active-session"]}))
        self.assertFalse(permits(self.policy, "dynamodb:PutItem", table, {"dynamodb:LeadingKeys": ["active-session"]}))

    def test_snapshot_creation_requires_exact_source_destination_and_tags(self):
        db = "arn:aws:rds:us-east-1:123456789012:db:deepresearch-staging"
        snapshot = "arn:aws:rds:us-east-1:123456789012:snapshot:deepresearch-staging-session-1-backup"
        context = {
            "aws:RequestTag/Project": "deepresearch", "aws:RequestTag/Environment": "staging",
            "aws:RequestTag/Session": "session-1", "aws:TagKeys": ["Project", "Environment", "Session"],
        }
        for resource in [db, snapshot]:
            self.assertTrue(permits(self.policy, "rds:CreateDBSnapshot", resource, context))
            self.assertFalse(permits(self.policy, "rds:CreateDBSnapshot", resource, {}))
            self.assertFalse(permits(self.policy, "rds:CreateDBSnapshot", resource.replace("staging", "production"), context))
        self.assertTrue(permits(self.policy, "rds:AddTagsToResource", snapshot, context))
        self.assertFalse(permits(self.policy, "rds:AddTagsToResource", db, context))
        self.assertFalse(permits(self.policy, "rds:CreateDBSnapshot", snapshot.replace("session-1", "session-2"), context))

    def test_policy_contains_no_destructive_or_permission_management_actions(self):
        actions = {action for statement in self.policy["Statement"] for action in statement["Action"]}
        self.assertFalse(any("*" in action or action.startswith(("iam:", "ec2:", "secretsmanager:")) for action in actions))
        self.assertEqual({"dynamodb:DeleteItem"}, {action for action in actions if ":Delete" in action})
        self.assertFalse(any("*" == resource for statement in self.policy["Statement"] for resource in statement["Resource"]))
        self.assertNotIn("rds:ModifyDBInstance", actions)

    def test_metadata_reads_never_cover_other_environment_or_account(self):
        requests = [
            ("eks:DescribeCluster", "arn:aws:eks:us-east-1:123456789012:cluster/deepresearch-staging"),
            ("cognito-idp:DescribeUserPool", "arn:aws:cognito-idp:us-east-1:123456789012:userpool/us-east-1_pool123"),
            ("sns:GetTopicAttributes", CONFIG["alert_topic_arn"]),
            ("kms:DescribeKey", CONFIG["alert_kms_key_arn"]),
            ("rds:DescribeDBSnapshots", "arn:aws:rds:us-east-1:123456789012:snapshot:deepresearch-staging-session-1-backup"),
        ]
        for action, resource in requests:
            with self.subTest(action=action):
                self.assertTrue(permits(self.policy, action, resource))
                self.assertFalse(permits(self.policy, action, resource.replace("123456789012", "999999999999")))
                self.assertFalse(permits(self.policy, action, resource.replace("us-east-1", "us-west-2")))
                if "staging" in resource:
                    self.assertFalse(permits(self.policy, action, resource.replace("staging", "production")))

    def test_runner_kms_inventory_permission_is_exact_and_optional(self):
        key_arn = "arn:aws:kms:us-east-1:123456789012:key/22222222-2222-4222-8222-222222222222"
        policy = backup_policy({**CONFIG, "runner_token_kms_key_arn": key_arn})
        self.assertTrue(permits(policy, "kms:DescribeKey", key_arn))
        self.assertTrue(permits(policy, "kms:ListResourceTags", key_arn))
        self.assertFalse(permits(policy, "kms:DescribeKey", key_arn.replace("123456789012", "999999999999")))
        self.assertFalse(permits(self.policy, "kms:DescribeKey", key_arn))

    def test_invalid_config_is_rejected_without_mutating_input(self):
        original = copy.deepcopy(CONFIG)
        backup_policy(CONFIG)
        self.assertEqual(original, CONFIG)
        for field, value in [("session_id", "session/*"), ("session_id", "x" * 17), ("user_pool_id", "us-west-2_pool123"), ("backup_bucket", "unrelated-bucket"), ("account_id", "*")]:
            with self.subTest(field=field, value=value):
                invalid = {**CONFIG, field: value}
                with self.assertRaises(Refused):
                    backup_policy(invalid)
